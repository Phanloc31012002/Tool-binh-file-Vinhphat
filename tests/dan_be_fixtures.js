function circle(radius, count) {
  const points = [];
  for (let i = 0; i < (count || 96); i++) {
    const a = (i * Math.PI * 2) / (count || 96);
    points.push([radius + radius * Math.cos(a), radius + radius * Math.sin(a)]);
  }
  return [[points]];
}
